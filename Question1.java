public class Question1{

    // main method
    public static void main(String[] args){
        int count = 10;

        // writes a while loop that counts down from 10-1.
        while(count > 0){
            System.out.println(count);
            count--;
        }
        //prints liftoff! after the loop finishes counting.
        System.out.println("Liftoff!");
    }

}